type LauncherMode = "tui" | "shell" | "command";

const BASE_ENV_KEYS = ["USER", "LOGNAME", "LANG"] as const;
const INTERACTIVE_ENV_KEYS = [
  "TERM",
  "COLORTERM",
  "TERMINFO",
  "DISPLAY",
  "WAYLAND_DISPLAY",
  "XDG_RUNTIME_DIR",
  "XDG_SESSION_CLASS",
  "XDG_SESSION_DESKTOP",
  "XDG_SESSION_TYPE",
  "XDG_CURRENT_DESKTOP",
  "DBUS_SESSION_BUS_ADDRESS",
] as const;

function copyDefinedEnvKey(
  sourceEnv: NodeJS.ProcessEnv,
  targetEnv: Record<string, string | undefined>,
  key: string
): void {
  const value = sourceEnv[key];
  if (value !== undefined && value !== "") {
    targetEnv[key] = value;
  }
}

function buildChildEnv(
  mode: LauncherMode,
  isolatedEnv: Record<string, string | undefined>,
  extraPathDirs: string[] = [],
  sourceEnv: NodeJS.ProcessEnv = process.env
): Record<string, string | undefined> {
  // Child env is intentionally allowlist-only to preserve e2e isolation parity.
  // Do not spread process.env here.
  const childEnv: Record<string, string | undefined> = {
    PATH: [...extraPathDirs, sourceEnv.PATH ?? ""].filter((entry) => entry && entry.length > 0).join(":"),
  };

  for (const key of BASE_ENV_KEYS) {
    copyDefinedEnvKey(sourceEnv, childEnv, key);
  }

  for (const [key, value] of Object.entries(sourceEnv)) {
    if (key.startsWith("LC_") && value !== undefined && value !== "") {
      childEnv[key] = value;
    }
  }

  if (mode === "tui" || mode === "shell") {
    for (const key of INTERACTIVE_ENV_KEYS) {
      copyDefinedEnvKey(sourceEnv, childEnv, key);
    }
  }

  if (mode === "shell") {
    copyDefinedEnvKey(sourceEnv, childEnv, "SHELL");
  }

  return {
    ...childEnv,
    ...isolatedEnv,
  };
}

export async function ensureInteractiveShellStartupReady(
  shellPath: string,
  env: Record<string, string | undefined>
): Promise<void> {
  const shellName = basename(shellPath).toLowerCase();
  if (shellName !== "zsh") {
    return;
  }

  const homeDir = env.HOME?.trim();
  if (!homeDir) {
    return;
  }

  const zdotdir = env.ZDOTDIR?.trim() || homeDir;
  const zshrcPath = join(zdotdir, ".zshrc");
  const existing = await stat(zshrcPath).catch(() => null);
  if (existing) {
    return;
  }

  await mkdir(zdotdir, { recursive: true });
  await writeFile(
    zshrcPath,
    "# Generated by opencode-coder manual launcher for isolated shell sessions.\n",
    "utf8"
  );
}

